import { mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { expandFindings } from "./live-baseline.mjs";
import { directory } from "./references.js";

type Report = {
  dialect: string;
  target: { version: string };
  categories: Record<string, { count?: number; status: string; observations?: { name: string; status: string }[] }>;
};
type NativeFinding = {
  dialect: string;
  target: {
    version: string;
    modeProfile?: string;
    adapter?: string;
    platform?: string;
    arch?: string;
    settings?: { compatibilityLevel?: number };
  };
  counts: Record<string, number>;
  observations: { name: string; status: string }[];
};
const context = (target: NativeFinding["target"]) =>
  `${target.version}${target.modeProfile ? ` / ${target.modeProfile}` : ""}${target.adapter ? ` / ${target.adapter}` : ""}${target.platform ? ` / ${target.platform}-${target.arch}` : ""}${target.settings?.compatibilityLevel ? ` / compatibility ${target.settings.compatibilityLevel}` : ""}`;

export async function renderReport(check = false) {
  const { reports }: { reports: Report[] } = JSON.parse(await readFile(resolve(directory, "baseline.json"), "utf8"));
  const lines = [
    "# Language audit: function gaps and inventory coverage",
    "",
    "Generated by `pnpm audit:language:report`. The machine-readable baseline in `test/fixtures/language-audit/baseline.json` contains every observed name and classification. Upstream inventories are independent of typed-sql mappings.",
    "",
    "## How to read this audit",
    "",
    "`unknown-function-observed` means a name is absent from the selected grammar's builtin catalog and generated scalar recognition probes produced an unknown-function diagnostic. These are mapping-gap candidates, not proof that every upstream overload is valid in a SELECT expression. Table functions, special syntax, platform restrictions, extensions, and version availability still need review.",
    "",
    "`invocation-unverified` means generated NULL-argument calls could not establish recognition. It is a coverage gap, not a confirmed missing function. `declared-semantics-unverified` and `typed-recognition-semantics-unverified` establish declaration or recognition only; neither proves overload correctness, nullability, runtime decoding, or full SQL support.",
    "",
    "The SQLite reference is unversioned and can include compile-option or extension functions. Live captures qualify only their exact recorded engine/build. DuckDB live catalogs include macros, table functions, and symbolic operators. Internal PostgreSQL routines and SQL Server system objects are distinct from the public function reference inventory.",
    "",
    "## Coverage",
    "",
    "A number means the upstream inventory was observed. `—` means unavailable in that source, with the reason recorded in the baseline. Discovery coverage and semantic coverage are separate; unavailable and unverified categories never count as supported.",
    "",
    "| Grammar | Inventory target | Functions | Keywords | Types | Operators | Casts | Collations | Settings | Extensions | Syntax |",
    "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
  ];
  const categories = [
    "functions",
    "keywords",
    "types",
    "operators",
    "casts",
    "collations",
    "settings",
    "extensions",
    "syntax",
  ];
  for (const report of reports)
    lines.push(
      `| ${report.dialect} | ${report.target.version} | ${categories.map((category) => report.categories[category]?.count ?? "—").join(" | ")} |`,
    );
  lines.push(
    "",
    "## Function findings",
    "",
    "Names below are generated from upstream inventories. Versions sharing a finding are grouped to avoid repeating the same list for every supported version.",
    "",
  );
  for (const dialect of [...new Set(reports.map((report) => report.dialect))]) {
    lines.push(
      `### ${dialect}`,
      "",
      "| Target | Names observed | Unknown-function observations | Unverified invocations | Declared or typed recognition |",
      "| --- | ---: | ---: | ---: | ---: |",
    );
    const selected = reports.filter((report) => report.dialect === dialect);
    for (const report of selected) {
      const observations = report.categories.functions!.observations!;
      const count = (status: string) => observations.filter((row) => row.status === status).length;
      lines.push(
        `| ${report.target.version} | ${observations.length} | ${count("unknown-function-observed")} | ${count("invocation-unverified") + count("special-syntax-unverified")} | ${count("declared-semantics-unverified") + count("typed-recognition-semantics-unverified")} |`,
      );
    }
    for (const status of ["unknown-function-observed", "invocation-unverified", "special-syntax-unverified"]) {
      const groups = new Map<string, string[]>();
      const allNames = [
        ...new Set(
          selected.flatMap((report) =>
            report.categories.functions!.observations!.filter((row) => row.status === status).map((row) => row.name),
          ),
        ),
      ].sort();
      for (const name of allNames) {
        const versions = selected
          .filter((report) =>
            report.categories.functions!.observations!.some((row) => row.name === name && row.status === status),
          )
          .map((report) => report.target.version)
          .join(", ");
        const names = groups.get(versions) ?? [];
        names.push(name);
        groups.set(versions, names);
      }
      if (groups.size) lines.push("", `**${status}**`, "");
      for (const [versions, names] of groups)
        lines.push(`Targets ${versions}:`, "", `${names.map((name) => `\`${name}\``).join(", ")}.`, "");
    }
  }
  const native = expandFindings(JSON.parse(await readFile(resolve(directory, "native-findings.json"), "utf8"))) as {
    targets: Record<string, NativeFinding>;
  };
  lines.push(
    "## Native preparation confirms analysis differences",
    "",
    "These calls were accepted by the exact engine's prepare/describe operation. The grammar then emitted diagnostics or inferred an unknown result. Preparation does not prove runtime success or full result semantics. Engine-only/internal routines, unmodeled result types, and deliberate fail-closed policies can account for differences; they require classification rather than optimistic mappings.",
    "",
    "Every differing invocation and its diagnostics are recorded in `test/fixtures/language-audit/native-findings.json`. The lists below include all observed names with differences, including engine-only names absent from the public function manuals.",
    "",
    "| Grammar | Exact native context | Valid calls with diagnostics | Valid calls with unknown result | Valid recognized calls |",
    "| --- | --- | ---: | ---: | ---: |",
  );
  const nativeTargets = Object.entries(native.targets)
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([, value]) => value);
  for (const value of nativeTargets)
    lines.push(
      `| ${value.dialect} | ${context(value.target)} | ${value.counts["native-valid-grammar-diagnostic"] ?? 0} | ${value.counts["native-valid-grammar-unknown"] ?? 0} | ${value.counts["native-valid-recognition-only"] ?? 0} |`,
    );
  lines.push("");
  for (const value of nativeTargets) {
    lines.push(`### ${value.dialect} ${context(value.target)}`, "");
    for (const status of ["native-valid-grammar-diagnostic", "native-valid-grammar-unknown"]) {
      const names = [
        ...new Set(value.observations.filter((row) => row.status === status).map((row) => row.name)),
      ].sort();
      if (names.length)
        lines.push(
          `**${status}** (${names.length} names):`,
          "",
          `${names.map((name) => `\`${name}\``).join(", ")}.`,
          "",
        );
    }
  }
  lines.push(
    "## Remaining verification",
    "",
    "Full overload and semantic verification requires valid typed/domain-specific inputs, aggregate/window/table contexts, parameters and source spans, nullability counterexamples, session settings, negative cases, and runtime decoding checks. This inventory audit does not replace the grammar conformance suites. It makes these limitations and upstream drift reviewable rather than claiming completeness from a hand-maintained fixture list.",
    "",
  );
  const output = resolve("planning/language-audit/missing-functions.md");
  const value = lines.join("\n");
  if (check) {
    if ((await readFile(output, "utf8")) !== value)
      throw new Error("Language audit report is stale: run pnpm audit:language:report");
  } else {
    await mkdir(resolve("planning/language-audit"), { recursive: true });
    await writeFile(output, value);
  }
  console.log(output);
}
