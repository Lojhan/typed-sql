import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname } from "node:path";
import { hash } from "../language-audit/hash.mjs";
import { duckdbCombinations, duckdbSignature, groupCorpus, postgresSignature } from "./model.mjs";
import { generationReport, renderGenerationReport } from "./report.mjs";
import { sqlServerTypeSource } from "./sqlserver.mjs";

const root = new URL("../../", import.meta.url);
const header = "// Generated by pnpm catalog:generate. Edit captured facts or grammar policy, not this file.\n";
const unique = (rows) => [...new Map(rows.map((row) => [JSON.stringify(row), row])).values()];
const ordered = (rows) => unique(rows).sort((a, b) => JSON.stringify(a).localeCompare(JSON.stringify(b)));
const literal = (value) =>
  JSON.stringify(value, (_key, child) => (child === Infinity ? "$unbounded" : child)).replaceAll(
    '"$unbounded"',
    "Number.POSITIVE_INFINITY",
  );
const rowsLiteral = (rows) => `[\n${rows.map((row) => `  ${literal(row)},`).join("\n")}\n]`;

async function output(path, text, check, changed) {
  const file = new URL(path, root);
  const current = await readFile(file, "utf8").catch((error) => {
    if (error.code !== "ENOENT") throw error;
    return "";
  });
  if (text === current) return;
  changed.push(path);
  if (check) return;
  await mkdir(dirname(file.pathname), { recursive: true });
  await writeFile(file, text);
}

export function validateParserPolicy(parser) {
  for (const name of ["keywords", "operators"]) {
    if (!Array.isArray(parser[name]) || !parser[name].length || new Set(parser[name]).size !== parser[name].length)
      throw new Error(`Parser ${name} must be nonempty and unique`);
    if (parser[name].some((value) => typeof value !== "string" || !value)) throw new Error(`Invalid parser ${name}`);
  }
  if (parser.keywords.some((name) => !/^[A-Z_][A-Z_0-9]*$/u.test(name))) throw new Error("Invalid parser keyword");
  parser.operators.forEach((operator, index) => {
    if (parser.operators.slice(index + 1).some((later) => later.startsWith(operator)))
      throw new Error(`Parser operator priority hides a longer token: ${operator}`);
  });
}

export function decodeFunctions(rows, sqlserver = false) {
  if (!Array.isArray(rows) || !rows.length) throw new Error("Missing function policy");
  const identities = new Set();
  return rows.map((row) => {
    if (!/^[A-Z_][A-Z_0-9]*$/u.test(row.name)) throw new Error(`Invalid policy function: ${row.name}`);
    const bounds = sqlserver ? [row.minimumArguments, row.maximumArguments] : row.arguments;
    if (
      !Array.isArray(bounds) ||
      bounds.length !== 2 ||
      !Number.isSafeInteger(bounds[0]) ||
      bounds[0] < 0 ||
      !(bounds[1] === "unbounded" || (Number.isSafeInteger(bounds[1]) && bounds[1] >= bounds[0]))
    )
      throw new Error(`Invalid argument bounds: ${row.name}`);
    if (!["scalar", "aggregate", "window", "table"].includes(row.kind) || typeof (row.rule ?? row.result) !== "string")
      throw new Error(`Missing semantic policy: ${row.name}`);
    const identity = JSON.stringify([row.name, row.kind, bounds, row.availableSince ?? row.since ?? null]);
    if (identities.has(identity)) throw new Error(`Duplicate function policy: ${row.name}`);
    identities.add(identity);
    const maximum = bounds[1] === "unbounded" ? Infinity : bounds[1];
    return sqlserver ? { ...row, maximumArguments: maximum } : { ...row, arguments: [bounds[0], maximum] };
  });
}

/** @param {{check?: boolean, duckTypeName?: (name: string) => string, requiredTargets?: {dialect: string, version: string}[], sqliteTypes?: {name: string}[]}} options */
export async function generateCatalogs(corpus, options = {}) {
  const { check = false, duckTypeName, requiredTargets } = options;
  const changed = [];
  const outputs = [];
  const inputs = {};
  const emit = (path, text) => {
    outputs.push(path);
    return output(path, text, check, changed);
  };
  const groups = groupCorpus(corpus);
  for (const target of requiredTargets ?? [])
    if (!groups.some((group) => group.dialect === target.dialect && group.version === target.version))
      throw new Error(`Missing native generation input: ${target.dialect} ${target.version}`);
  for (const dialect of ["postgres", "mysql", "sqlite", "sqlserver"]) {
    const policy = JSON.parse(await readFile(new URL(`grammar/${dialect}/catalog/policy.json`, root), "utf8"));
    inputs[`${dialect}/policy`] = policy;
    if (["postgres", "mysql"].includes(dialect))
      inputs[`${dialect}/core`] = JSON.parse(
        await readFile(new URL(`grammar/${dialect}/catalog/core.json`, root), "utf8"),
      );
    if (policy.formatVersion !== 1) throw new Error(`Unsupported ${dialect} generation policy`);
    if (policy.parser) {
      validateParserPolicy(policy.parser);
      await emit(
        `packages/${dialect}/src/parser/vocabulary.generated.ts`,
        `${header}export const parserKeywords = ${rowsLiteral(policy.parser.keywords)} as const;\nexport const parserOperators = ${rowsLiteral(policy.parser.operators)} as const;\n`,
      );
    }
    if (dialect === "postgres") {
      for (const value of Object.values(policy.syntaxVolatility))
        if (!["immutable", "stable", "volatile", "unknown"].includes(value))
          throw new Error("Invalid syntax volatility policy");
      await emit(
        "packages/postgres/src/catalog/generated/semantics.ts",
        `${header}import type { QueryVolatility } from "@typed-sql/core";\nexport const syntaxVolatility: Readonly<Record<string, QueryVolatility>> = ${literal(policy.syntaxVolatility)};\n`,
      );
    }
    if (dialect === "sqlite") {
      let source = `${header}import type { SqliteBuiltinDefinition, SqliteTableFunctionDefinition } from "../functions.js";\nimport type { SqliteOperatorDefinition } from "../operators.js";\n`;
      for (const [family, rows] of Object.entries(policy.functions))
        source += `export const ${family}Functions: readonly SqliteBuiltinDefinition[] = Object.freeze(${rowsLiteral(decodeFunctions(rows))});\n`;
      for (const [family, rows] of Object.entries(policy.tableFunctions)) {
        for (const row of rows) {
          if (
            !row.availableSince ||
            !/^[A-Z_][A-Z_0-9]*$/u.test(row.name) ||
            !["carray", "json", "jsonb"].includes(row.result)
          )
            throw new Error(`Invalid table-function policy: ${row.name}`);
        }
        source += `export const ${family}TableFunctions: readonly SqliteTableFunctionDefinition[] = Object.freeze(${rowsLiteral(rows)});\n`;
      }
      source += `export const operators: readonly SqliteOperatorDefinition[] = Object.freeze(${rowsLiteral(policy.operators)});\n`;
      source += `export const unsupportedOperators = ${rowsLiteral(policy.unsupportedOperators)} as const;\n`;
      source += `export const currentTimeKeywords = ${rowsLiteral(policy.currentTimeKeywords)} as const;\n`;
      await emit("packages/sqlite/src/catalog/generated/policy.ts", source);
      if (!options.sqliteTypes?.length) throw new Error("Missing independent SQLite STRICT type inventory");
      const strict = {};
      for (const row of options.sqliteTypes) {
        const mapping = policy.strictTypes[row.name];
        if (!["integer", "number", "string", "bytes", "flexible"].includes(mapping))
          throw new Error(`Missing SQLite STRICT decoding policy: ${row.name}`);
        strict[row.name] = mapping;
      }
      if (Object.keys(policy.strictTypes).some((name) => !Object.hasOwn(strict, name)))
        throw new Error("SQLite STRICT type policy refers to a name absent from the upstream inventory");
      await emit(
        "packages/sqlite/src/catalog/generated/types.ts",
        `${header}import type { SqliteAffinity } from "../coercions.js";\nexport const strictTypeMappings: Readonly<Record<string, "integer" | "number" | "string" | "bytes" | "flexible">> = ${literal(strict)};\nexport const affinityRules: readonly { readonly affinity: SqliteAffinity; readonly contains: readonly string[]; readonly empty?: boolean }[] = ${rowsLiteral(policy.affinityRules)};\nexport const defaultAffinity: SqliteAffinity = ${literal(policy.defaultAffinity)};\nexport const numericTypeNames: readonly string[] = ${rowsLiteral(policy.numericTypeNames)};\n`,
      );
    }
    if (dialect === "sqlserver") {
      const entries = decodeFunctions(policy.functions, true);
      await emit("packages/sqlserver/src/catalog/generated/types.ts", sqlServerTypeSource(policy, groups, header));
      await emit(
        "packages/sqlserver/src/catalog/generated/policy.ts",
        `${header}import type { SqlServerBuiltin } from "../index.js";\nexport const builtinEntries: readonly SqlServerBuiltin[] = Object.freeze(${rowsLiteral(entries)});\nexport const dateparts = ${rowsLiteral(policy.dateparts)} as const;\n`,
      );
    }
  }

  const postgres = groups.filter((group) => group.dialect === "postgres");
  const shared = ordered(
    postgres.flatMap((group) => group.categories.functions.rows.map(postgresSignature).filter(Boolean)),
  );
  const indexes = new Map(shared.map((signature, index) => [JSON.stringify(signature), index]));
  let native = `${header}import type { PostgresNativeSignature } from "../native.js";\nconst entries: readonly PostgresNativeSignature[] = ${rowsLiteral(shared)};\nexport const nativeSignatures: Readonly<Record<number, readonly PostgresNativeSignature[]>> = {\n`;
  for (const group of postgres) {
    const signatures = ordered(group.categories.functions.rows.map(postgresSignature).filter(Boolean));
    native += `  ${group.version}: [${signatures.map((signature) => `entries[${indexes.get(JSON.stringify(signature))}]!`).join(",")}],\n`;
  }
  native += "};\n";
  await emit("packages/postgres/src/catalog/generated/native.ts", native);

  const duckdb = groups.filter((group) => group.dialect === "duckdb");
  const duckPolicy = JSON.parse(await readFile(new URL("grammar/duckdb/catalog/policy.json", root), "utf8"));
  inputs["duckdb/policy"] = duckPolicy;
  if (
    duckPolicy.formatVersion !== 1 ||
    new Set(duckPolicy.macroSignatures.map((entry) => entry.name)).size !== duckPolicy.macroSignatures.length
  )
    throw new Error("Invalid DuckDB macro policy");
  let duckRegistry = `${header}${duckdb.map((group, index) => `import { signatures as signatures${index}, implicitCasts as casts${index} } from "./${group.version}.js";\nimport { commonTypes as common${index}, expressionTypes as expression${index} } from "./common-${group.version}.js";`).join("\n")}\n`;
  duckRegistry += `export const nativeCatalogs = {${duckdb.map((group, index) => `${JSON.stringify(group.version)}: signatures${index}`).join(",")}};\n`;
  duckRegistry += `export const nativeImplicitCasts = {${duckdb.map((group, index) => `${JSON.stringify(group.version)}: casts${index}`).join(",")}};\n`;
  duckRegistry += `export const nativeCommonTypes: Readonly<Record<string, Readonly<Record<string, string | null>>>> = {${duckdb.map((group, index) => `${JSON.stringify(group.version)}: common${index}`).join(",")}};\n`;
  duckRegistry += `export const nativeExpressionTypes: Readonly<Record<string, Readonly<Record<string, string | null>>>> = {${duckdb.map((group, index) => `${JSON.stringify(group.version)}: expression${index}`).join(",")}};\n`;
  await emit("packages/duckdb/src/catalog/generated/registry.ts", duckRegistry);
  const duckAliases = {};
  for (const group of duckdb) {
    if (!duckTypeName) throw new Error("DuckDB canonical type policy is required");
    const combinations = JSON.parse(
      await readFile(new URL(`grammar/duckdb/catalog/combinations-${group.version}.json`, root), "utf8"),
    );
    inputs[`duckdb/combinations/${group.version}`] = combinations;
    const nativeName = (name) => {
      const descriptor = combinations.aliases[name];
      if (!descriptor || combinations.unavailable.some((entry) => entry.name === name)) {
        const logical = group.categories.types.rows.find((entry) => entry.name === name)?.logical_type;
        return ["NULL", "ANY", "INVALID", "UNKNOWN"].includes(logical) ? logical : duckTypeName(name);
      }
      const spelling = descriptor.replace(/\(.*\)$/u, "");
      return duckTypeName(duckPolicy.typeSpellings[spelling] ?? spelling);
    };
    for (const [alias, nativeType] of Object.entries(combinations.aliases)) {
      if (combinations.unavailable.some((entry) => entry.name === alias)) continue;
      const spelling = nativeType.replace(/\(.*\)$/u, "");
      const canonical = duckPolicy.typeSpellings[spelling] ?? spelling;
      const name = alias.toUpperCase();
      if (duckAliases[name] && duckAliases[name] !== canonical)
        throw new Error(`Conflicting DuckDB type alias: ${alias}`);
      if (name !== canonical) duckAliases[name] = canonical;
    }
    const matrices = duckdbCombinations(combinations, group.version, nativeName);
    await emit(
      `packages/duckdb/src/catalog/generated/common-${group.version}.ts`,
      `${header}export const commonTypes: Readonly<Record<string, string | null>> = ${literal(matrices.set)};\nexport const expressionTypes: Readonly<Record<string, string | null>> = ${literal(matrices.expression)};\n`,
    );
    const signatures = ordered(
      group.categories.functions.rows.map((row) => duckdbSignature(row, duckPolicy.macroSignatures)),
    );
    const typeNames = new Map(group.categories.types.rows.map((row) => [row.name, nativeName(row.name)]));
    const casts = ordered(
      group.categories.casts.rows
        .filter((row) => row.implicit)
        .map((row) => {
          const [source, target] = row.name.split(" -> ");
          if (!typeNames.has(source) || !typeNames.has(target))
            throw new Error(`Missing DuckDB cast endpoint: ${row.name}`);
          return [typeNames.get(source), typeNames.get(target)];
        }),
    );
    const revision = hash({ signatures, casts });
    await emit(
      `packages/duckdb/src/catalog/generated/${group.version}.ts`,
      `${header}// Captured facts ${revision}\nimport type { DuckDBBuiltinSignature } from "../types.js";\nexport const signatures: readonly DuckDBBuiltinSignature[] = ${rowsLiteral(signatures)};\nexport const implicitCasts: readonly (readonly [string, string])[] = ${rowsLiteral(casts)};\n`,
    );
  }
  await emit(
    "packages/duckdb/src/catalog/generated/aliases.ts",
    `${header}export const nativeTypeAliases: Readonly<Record<string, string>> = ${literal(Object.fromEntries(Object.entries(duckAliases).sort(([a], [b]) => a.localeCompare(b))))};\n`,
  );
  inputs.sqliteTypes = options.sqliteTypes;
  const report = generationReport(corpus, groups, inputs, outputs);
  await output("grammar/catalog/generation.json", `${JSON.stringify(report, null, 2)}\n`, check, changed);
  await output("planning/language-audit/generation.md", renderGenerationReport(report), check, changed);
  if (check && changed.length)
    throw new Error(`Generated catalogs are stale; run pnpm catalog:generate:\n${changed.join("\n")}`);
  return { groups, changed };
}
