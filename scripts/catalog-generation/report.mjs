import { hash } from "../language-audit/hash.mjs";
import { CATEGORIES } from "../language-audit/inventory.mjs";

export function generationReport(corpus, groups, inputs, outputs, catalog = undefined) {
  return {
    formatVersion: 1,
    inputFingerprint: hash({ contexts: corpus.targets, inputs }),
    ...(catalog
      ? {
          model: {
            formatVersion: catalog.formatVersion,
            schemaDigest: catalog.schemaDigest,
            normalizerDigest: catalog.normalizerDigest,
            inputDigest: catalog.inputDigest,
            profiles: Object.keys(catalog.profiles).length,
            entities: Object.keys(catalog.entities).length,
            sources: Object.keys(catalog.sources).length,
          },
        }
      : {}),
    outputs: [...outputs].sort(),
    bands: groups.map((group) => ({
      dialect: group.dialect,
      version: group.version,
      contexts: group.contexts.map(({ id }) => id),
      categories: Object.fromEntries(
        CATEGORIES.map((name) => {
          const category = group.categories[name];
          return [
            name,
            category.status === "observed"
              ? {
                  status: category.status,
                  commonFacts: category.rows.length,
                  excludedContextFacts: category.excludedContextRows,
                }
              : { status: category.status, reasons: category.reasons },
          ];
        }),
      ),
    })),
  };
}

export function renderGenerationReport(report) {
  const lines = [
    "# Catalog generation evidence",
    "",
    "Generated by `pnpm catalog:generate`.",
    "",
    `Input revision: \`${report.inputFingerprint}\`.`,
    "",
    "Every category participates in the input revision, including categories without runtime consumers. Native facts do not prove semantic support. Context-specific facts are excluded from shared version catalogs and retained in the upstream corpus.",
    "",
    "The generators emit native PostgreSQL overloads/casts, DuckDB signatures/casts/common-type matrices, SQL Server physical type rules/aliases, and grammar-owned policy tables. SQLite STRICT names come from the independent official reference. Parser productions, coercion algorithms, nullability and decoding remain semantic policy; metadata cannot generate those rules by itself.",
    "",
    "| Grammar | Version | Contexts | Category | Shared facts | Context-specific facts |",
    "| --- | --- | ---: | --- | ---: | ---: |",
  ];
  if (report.model)
    lines.splice(
      8,
      0,
      `Validated model v${report.model.formatVersion}: ${report.model.profiles} profiles, ${report.model.entities} normalized entities, ${report.model.sources} source records. Schema ${report.model.schemaDigest}; normalizer ${report.model.normalizerDigest}. Unknown provenance fields and semantic gaps remain unverified.`,
      "",
    );
  for (const band of report.bands)
    for (const [name, category] of Object.entries(band.categories))
      lines.push(
        `| ${band.dialect} | ${band.version} | ${band.contexts.length} | ${name} | ${category.status === "observed" ? category.commonFacts : "unavailable"} | ${category.status === "observed" ? category.excludedContextFacts : "—"} |`,
      );
  lines.push("", "## Unavailable evidence", "");
  const limitations = new Set(
    report.bands.flatMap((band) =>
      Object.entries(band.categories)
        .filter(([, category]) => category.status === "unavailable")
        .flatMap(([name, category]) => category.reasons.map((reason) => `${band.dialect} ${name}: ${reason}`)),
    ),
  );
  for (const limitation of [...limitations].sort()) lines.push(`- ${limitation}`);
  lines.push("", "## Generated runtime outputs", "");
  for (const output of report.outputs) lines.push(`- \`${output}\``);
  lines.push(
    "",
    "PostgreSQL/MySQL core catalog outputs and their version registries are also regenerated by the same command through their existing catalog generators.",
    "",
  );
  return lines.join("\n");
}
