/** Ownership marker shared by declaration writers and contract-aware checking. */
export const SQL_FILE_DECLARATION_HEADER = "// Generated by @typed-sql/build; regenerate with typed-sql-build types.\n";

/** Ignore only the known ownership comment and platform line endings, never declaration contents. */
export function comparableSqlDeclaration(source: string): string {
  const normalized = source.replaceAll("\r\n", "\n");
  return normalized.startsWith(SQL_FILE_DECLARATION_HEADER)
    ? normalized.slice(SQL_FILE_DECLARATION_HEADER.length)
    : normalized;
}
