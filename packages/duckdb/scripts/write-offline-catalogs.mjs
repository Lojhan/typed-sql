import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const policyFile = new URL("../../../grammar/duckdb/offline-core.json", import.meta.url);
const policyBytes = await readFile(policyFile);
const policy = JSON.parse(policyBytes);
if (policy.formatVersion !== 1 || typeof policy.selectionVersion !== "string" || typeof policy.basis !== "string")
  throw new TypeError("Invalid DuckDB offline core selection policy");
if (!policy.families || Array.isArray(policy.families) || !Array.isArray(policy.structuralForms))
  throw new TypeError("Offline core requires named families and explicit structural forms");
const names = Object.values(policy.families).flat();
if (
  names.some((name) => typeof name !== "string" || !/^[a-z][a-z_0-9]*$/u.test(name)) ||
  new Set(names).size !== names.length
)
  throw new TypeError("Offline core function names must be unique lower-case identities");
if (
  policy.structuralForms.some((name) => typeof name !== "string" || !/^[a-z][a-z_ ]*$/u.test(name)) ||
  new Set(policy.structuralForms).size !== policy.structuralForms.length
)
  throw new TypeError("Offline core structural forms must be unique lower-case identities");
const selected = new Set(names);
const digest = (bytes) => createHash("sha256").update(bytes).digest("hex");
async function publish(target, output, check) {
  const formatted = spawnSync("pnpm", ["exec", "biome", "format", "--stdin-file-path", fileURLToPath(target)], {
    input: output,
    encoding: "utf8",
    maxBuffer: 8 * 1024 * 1024,
  });
  if (formatted.status !== 0) throw Error(formatted.stderr);
  if (check) {
    if ((await readFile(target, "utf8")) !== formatted.stdout)
      throw Error(`Stale DuckDB catalog ${fileURLToPath(target)}`);
  } else {
    await mkdir(new URL(".", target), { recursive: true });
    await writeFile(target, formatted.stdout);
  }
}
export async function writeOfflineCatalogs(version, signatures, implicitCasts, check) {
  const knownBuiltinNames = [...new Set(signatures.map((row) => row[0]))].sort();
  const available = new Set(knownBuiltinNames);
  const missing = names.filter((name) => !available.has(name));
  if (missing.length) throw new TypeError(`Unknown DuckDB ${version} core functions: ${missing.join(", ")}`);
  // Retain complete overload families and all operators, with no shared or omitted rows.
  const included = (row) => selected.has(row[0]) || !/^[a-z_]/u.test(row[0]);
  const core = signatures.filter(included),
    longTail = signatures.filter((row) => !included(row));
  const combined = [...core, ...longTail].sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
  if (JSON.stringify(combined) !== JSON.stringify(signatures))
    throw Error("Native catalog order changed; refusing a lossy partition");
  const sourceDigest = digest(JSON.stringify({ signatures, casts: implicitCasts }));
  const selection = [...new Set([...core.map((row) => row[0]), ...policy.structuralForms])].sort();
  const provenance = { selectionVersion: policy.selectionVersion, policyDigest: digest(policyBytes), sourceDigest };
  const header = `// Generated by scripts/generate-offline-core.mjs from DuckDB ${version} native facts and maintained selection; do not edit.\n`;
  const coreOutput =
    header +
    `import type { DuckDBBuiltinSignature } from "../types.js";\nexport const provenance=${JSON.stringify(provenance)} as const;\nexport const signatures: readonly DuckDBBuiltinSignature[]=${JSON.stringify(core)};\nexport const implicitCasts: readonly (readonly [string,string])[]=${JSON.stringify(implicitCasts)};\nexport const knownBuiltinNames: readonly string[]=${JSON.stringify(knownBuiltinNames)};\nexport const selection: readonly string[]=${JSON.stringify(selection)};\n`;
  const tailOutput =
    header +
    `import type { DuckDBBuiltinSignature } from "../types.js";\nexport const signatures: readonly DuckDBBuiltinSignature[]=${JSON.stringify(longTail)};\n`;
  const fullOutput = `// Generated from DuckDB ${version} duckdb_functions() and can_cast_implicitly(); do not edit by hand.\n// Source snapshot sha256:${sourceDigest}\nimport {signatures as core} from "./core/${version}.js";\nimport {signatures as additional} from "./packs/${version}.js";\nimport type { DuckDBBuiltinSignature } from "./types.js";\n\nexport {implicitCasts} from "./core/${version}.js";\nexport const signatures: readonly DuckDBBuiltinSignature[]=[...core,...additional].sort((a,b)=>a[0]<b[0]?-1:a[0]>b[0]?1:0);\n`;
  await publish(new URL(`../src/catalog/core/${version}.ts`, import.meta.url), coreOutput, check);
  await publish(new URL(`../src/catalog/packs/${version}.ts`, import.meta.url), tailOutput, check);
  await publish(new URL(`../src/catalog/${version}.ts`, import.meta.url), fullOutput, check);
  console.log(
    `DuckDB ${version}: ${core.length} core + ${longTail.length} optional = ${signatures.length} native overloads; sha256:${sourceDigest}`,
  );
}
